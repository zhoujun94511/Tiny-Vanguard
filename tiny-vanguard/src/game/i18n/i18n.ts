export function translateUi(
  lang: LanguageCode,
  key: string,
  vars?: Record<string, string | number>
): string {
  const raw = UI_STRINGS[lang][key] ?? UI_STRINGS.zh[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export function translateContent(
  lang: LanguageCode,
  id: string,
  field: keyof ContentTextEntry,
  fallback: string
): string {
  if (lang === 'zh') return fallback;
  return CONTENT_EN[id]?.[field] ?? fallback;
}

export function formatDurationMMSS(sec: number): string {
  const s = Math.max(0, Math.floor(sec));
  const mm = Math.floor(s / 60);
  const ss = s % 60;
  return `${String(mm).padStart(2, '0')}:${String(ss).padStart(2, '0')}`;
}
